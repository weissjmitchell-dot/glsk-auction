-- Refresh the extension-cost reference from the current season's completed Auction sales.
create or replace function public.league_commish_refresh_extension_costs(
  p_room_code text,p_commish_pin text
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  with ranked as (
    select p.position,sa.price,row_number() over(partition by p.position order by sa.price desc,sa.sold_at asc) rn
    from public.sales sa join public.players p on p.id=sa.player_id
    where sa.room_id=v_room.id and sa.undone=false and p.position in ('QB','RB','WR','TE')
  ), top3 as (
    select position,max(price) filter(where rn=1) b1,max(price) filter(where rn=2) b2,max(price) filter(where rn=3) b3,
           avg(price::numeric) filter(where rn<=3) avg_bid,count(*) filter(where rn<=3) cnt
    from ranked group by position
  )
  insert into public.league_extension_costs(season_id,position,top_bid_1,top_bid_2,top_bid_3,average_bid,cost_2_to_3,cost_3_to_4,calculated_at)
  select v_season,position,b1,b2,b3,round(avg_bid,2),case when cnt=3 then round(avg_bid*0.25)::int end,
         case when cnt=3 then round(avg_bid*0.40)::int end,now() from top3
  on conflict(season_id,position) do update set top_bid_1=excluded.top_bid_1,top_bid_2=excluded.top_bid_2,top_bid_3=excluded.top_bid_3,
    average_bid=excluded.average_bid,cost_2_to_3=excluded.cost_2_to_3,cost_3_to_4=excluded.cost_3_to_4,calculated_at=now();
  return jsonb_build_object('ok',true);
end;
$$;

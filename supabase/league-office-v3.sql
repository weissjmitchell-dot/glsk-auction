-- ---------------------------------------------------------------------------
-- Extension-cost snapshot: actual top three Auction winning bids by position.
-- QB/RB/WR/TE only; K and D/ST intentionally excluded by league rule.
-- ---------------------------------------------------------------------------
with s as (
  select ls.id season_id,r.id room_id
  from public.league_seasons ls join public.rooms r on r.id=ls.room_id
  where r.code='GLSK26' and ls.is_current
), ranked as (
  select s.season_id,p.position,sa.price,
         row_number() over(partition by p.position order by sa.price desc,sa.sold_at asc) rn
  from s
  join public.sales sa on sa.room_id=s.room_id and sa.undone=false
  join public.players p on p.id=sa.player_id
  where p.position in ('QB','RB','WR','TE')
), top3 as (
  select season_id,position,
         max(price) filter(where rn=1) b1,
         max(price) filter(where rn=2) b2,
         max(price) filter(where rn=3) b3,
         avg(price::numeric) filter(where rn<=3) avg_bid,
         count(*) filter(where rn<=3) cnt
  from ranked group by season_id,position
)
insert into public.league_extension_costs(season_id,position,top_bid_1,top_bid_2,top_bid_3,average_bid,cost_2_to_3,cost_3_to_4,calculated_at)
select season_id,position,b1,b2,b3,round(avg_bid,2),
       case when cnt=3 then round(avg_bid*0.25)::int end,
       case when cnt=3 then round(avg_bid*0.40)::int end,
       now()
from top3
on conflict(season_id,position) do update
set top_bid_1=excluded.top_bid_1,top_bid_2=excluded.top_bid_2,top_bid_3=excluded.top_bid_3,
    average_bid=excluded.average_bid,cost_2_to_3=excluded.cost_2_to_3,cost_3_to_4=excluded.cost_3_to_4,
    calculated_at=now();


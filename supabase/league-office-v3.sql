-- ---------------------------------------------------------------------------
-- Drop penalty helper.
-- Year 1: double assigned contract points. Later years: 2yr=5, 3yr=10, 4yr=20.
-- ---------------------------------------------------------------------------
create or replace function public._league_drop_penalty(p_contract public.league_contracts,p_season_year integer)
returns integer language plpgsql immutable as $$
declare v_year integer;
begin
  if p_contract.id is null then return 0; end if;
  v_year:=greatest(1,p_season_year-p_contract.start_year+1);
  if v_year=1 then return p_contract.cap_cost*2; end if;
  return case p_contract.length_years when 2 then 5 when 3 then 10 when 4 then 20 else 0 end;
end;
$$;
revoke all on function public._league_drop_penalty(public.league_contracts,integer) from public,anon,authenticated;

create or replace function public.league_owner_drop_player(
  p_room_code text,p_team_id uuid,p_pin text,p_player_key text
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_room public.rooms%rowtype; v_season uuid; v_year integer;
  v_roster public.league_roster_entries%rowtype; v_contract public.league_contracts%rowtype;
  v_team public.teams%rowtype; v_penalty integer:=0; v_tx uuid;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_team_pin(p_team_id,p_pin) then raise exception 'Team authorization failed.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  select season_year into v_year from public.league_seasons where id=v_season;
  select * into v_team from public.teams where id=p_team_id and room_id=v_room.id for update;
  if v_team.id is null then raise exception 'Team not found.'; end if;
  select * into v_roster from public.league_roster_entries
    where room_id=v_room.id and team_id=p_team_id and player_key=p_player_key and active=true for update;
  if v_roster.id is null then raise exception 'That player is not on your active roster.'; end if;
  select * into v_contract from public.league_contracts
    where season_id=v_season and team_id=p_team_id and player_key=p_player_key and status='active' for update;
  if v_contract.id is not null then v_penalty:=public._league_drop_penalty(v_contract,v_year); end if;
  if v_team.remaining_budget<v_penalty then
    raise exception 'Drop blocked. Contract penalty is % bid dollars but you only have % remaining.',v_penalty,v_team.remaining_budget;
  end if;
  if v_penalty>0 then update public.teams set remaining_budget=remaining_budget-v_penalty where id=p_team_id; end if;
  update public.league_roster_entries set active=false,updated_at=now() where id=v_roster.id;
  if v_contract.id is not null then update public.league_contracts set status='released',updated_at=now() where id=v_contract.id; end if;
  update public.league_rookie_rights
    set status='extinguished',owner_team_id=null,extinguished_reason='player dropped',updated_at=now()
    where room_id=v_room.id and player_key=p_player_key and status='active';
  v_tx:=public._league_log_transaction(v_season,'drop',p_team_id,null,p_player_key,v_roster.player_name,
    v_roster.player_name||' dropped'||case when v_penalty>0 then ' • '||v_penalty||' bid-dollar contract penalty' else '' end,
    -v_penalty,case when v_contract.id is null then 0 else -v_contract.cap_cost end,
    'league_roster_entries',v_roster.id::text,null,
    jsonb_build_object('penalty',v_penalty,'contract_id',v_contract.id,'contract_length',v_contract.length_years,'contract_year',case when v_contract.id is null then null else greatest(1,v_year-v_contract.start_year+1) end,'rookie_rights_extinguished',exists(select 1 from public.league_rookie_rights where room_id=v_room.id and player_key=p_player_key and status='extinguished')));
  return jsonb_build_object('ok',true,'player',v_roster.player_name,'penalty',v_penalty,'transaction_id',v_tx,'remaining_budget',v_team.remaining_budget-v_penalty);
end;
$$;
grant execute on function public.league_owner_drop_player(text,uuid,text,text) to anon,authenticated;

create or replace function public.league_commish_exception_drop(
  p_room_code text,p_commish_pin text,p_team_id uuid,p_player_key text,p_reason text
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_roster public.league_roster_entries%rowtype; v_contract public.league_contracts%rowtype; v_tx uuid;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  if lower(coalesce(p_reason,'')) not in ('retirement','ban','banned') then raise exception 'No-penalty exception is only for retirement or ban.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  select * into v_roster from public.league_roster_entries where room_id=v_room.id and team_id=p_team_id and player_key=p_player_key and active=true for update;
  if v_roster.id is null then raise exception 'Active roster player not found.'; end if;
  select * into v_contract from public.league_contracts where season_id=v_season and team_id=p_team_id and player_key=p_player_key and status='active' for update;
  update public.league_roster_entries set active=false,updated_at=now() where id=v_roster.id;
  if v_contract.id is not null then update public.league_contracts set status='void',updated_at=now() where id=v_contract.id; end if;
  update public.league_rookie_rights set status='extinguished',owner_team_id=null,extinguished_reason=p_reason,updated_at=now()
    where room_id=v_room.id and player_key=p_player_key and status='active';
  v_tx:=public._league_log_transaction(v_season,'contract_voided',p_team_id,null,p_player_key,v_roster.player_name,
    v_roster.player_name||' removed • contract voided for '||p_reason||' • no penalty',0,
    case when v_contract.id is null then 0 else -v_contract.cap_cost end,'league_roster_entries',v_roster.id::text,null,
    jsonb_build_object('reason',p_reason,'contract_id',v_contract.id));
  return jsonb_build_object('ok',true,'transaction_id',v_tx);
end;
$$;
grant execute on function public.league_commish_exception_drop(text,text,uuid,text,text) to anon,authenticated;

-- ---------------------------------------------------------------------------
-- Trade validation helper. Enforces ownership, one-year-ahead pick rule,
-- bid-dollar availability, and the 100-point contract cap BEFORE a trade can proceed.
-- ---------------------------------------------------------------------------
create or replace function public._league_validate_trade(p_trade_id uuid)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_trade public.league_trades%rowtype; v_season public.league_seasons%rowtype; v_room_id uuid;
  a record; v_owner uuid; v_other uuid; v_give_bid integer:=0; v_receive_bid integer:=0;
  v_prop_cap integer; v_partner_cap integer; v_prop_out integer:=0; v_prop_in integer:=0; v_part_out integer:=0; v_part_in integer:=0;
  v_limit integer;
begin
  select * into v_trade from public.league_trades where id=p_trade_id;
  if v_trade.id is null then return jsonb_build_object('ok',false,'error','Trade not found.'); end if;
  select * into v_season from public.league_seasons where id=v_trade.season_id;
  v_room_id:=v_season.room_id; v_limit:=v_season.salary_cap_points;
  select coalesce(sum(cap_cost),0) into v_prop_cap from public.league_contracts where season_id=v_season.id and team_id=v_trade.proposer_team_id and status='active';
  select coalesce(sum(cap_cost),0) into v_partner_cap from public.league_contracts where season_id=v_season.id and team_id=v_trade.partner_team_id and status='active';

  for a in select * from public.league_trade_assets where trade_id=p_trade_id loop
    v_owner:=case when a.direction='proposer_to_partner' then v_trade.proposer_team_id else v_trade.partner_team_id end;
    v_other:=case when a.direction='proposer_to_partner' then v_trade.partner_team_id else v_trade.proposer_team_id end;
    if a.asset_type='player' then
      if not exists(select 1 from public.league_roster_entries where room_id=v_room_id and team_id=v_owner and player_key=a.asset_key and active=true) then
        return jsonb_build_object('ok',false,'error',coalesce(a.player_name,a.asset_key)||' is no longer owned by the sending team.');
      end if;
      if a.direction='proposer_to_partner' then
        select coalesce(cap_cost,0) into v_prop_out from public.league_contracts where season_id=v_season.id and team_id=v_owner and player_key=a.asset_key and status='active';
        v_prop_out:=coalesce(v_prop_out,0);
        v_part_in:=v_part_in+v_prop_out;
      else
        select coalesce(cap_cost,0) into v_part_out from public.league_contracts where season_id=v_season.id and team_id=v_owner and player_key=a.asset_key and status='active';
        v_part_out:=coalesce(v_part_out,0);
        v_prop_in:=v_prop_in+v_part_out;
      end if;
    elsif a.asset_type='rookie_rights' then
      if not exists(select 1 from public.league_rookie_rights where room_id=v_room_id and player_key=a.asset_key and owner_team_id=v_owner and status='active') then
        return jsonb_build_object('ok',false,'error','Rookie rights are no longer owned by the sending team.');
      end if;
      if exists(select 1 from public.league_trade_assets x where x.trade_id=p_trade_id and x.asset_type='player' and x.asset_key=a.asset_key) then
        return jsonb_build_object('ok',false,'error','Do not add rookie rights separately when the same player is in the trade; rights transfer automatically with the player.');
      end if;
    elsif a.asset_type in ('rookie_pick','supplemental_pick') then
      if a.pick_id is null or not exists(
        select 1 from public.league_future_picks fp where fp.id=a.pick_id and fp.room_id=v_room_id and fp.owner_team_id=v_owner and fp.status='active'
          and fp.draft_year=v_season.season_year+1
          and fp.draft_type=case when a.asset_type='rookie_pick' then 'rookie' else 'supplemental' end
      ) then return jsonb_build_object('ok',false,'error','That future draft pick is not currently tradable by the sending team.'); end if;
    elsif a.asset_type='bid_dollars' then
      if a.direction='proposer_to_partner' then v_give_bid:=v_give_bid+coalesce(a.bid_amount,0); else v_receive_bid:=v_receive_bid+coalesce(a.bid_amount,0); end if;
    end if;
  end loop;

  if v_give_bid>(select remaining_budget from public.teams where id=v_trade.proposer_team_id) then return jsonb_build_object('ok',false,'error','Proposer does not have enough bid dollars.'); end if;
  if v_receive_bid>(select remaining_budget from public.teams where id=v_trade.partner_team_id) then return jsonb_build_object('ok',false,'error','Partner does not have enough bid dollars.'); end if;

  -- Sum outgoing player contract points correctly, independent of row loop ordering.
  select coalesce(sum(c.cap_cost),0) into v_prop_out
  from public.league_trade_assets a join public.league_contracts c on c.season_id=v_season.id and c.team_id=v_trade.proposer_team_id and c.player_key=a.asset_key and c.status='active'
  where a.trade_id=p_trade_id and a.direction='proposer_to_partner' and a.asset_type='player';
  select coalesce(sum(c.cap_cost),0) into v_part_out
  from public.league_trade_assets a join public.league_contracts c on c.season_id=v_season.id and c.team_id=v_trade.partner_team_id and c.player_key=a.asset_key and c.status='active'
  where a.trade_id=p_trade_id and a.direction='partner_to_proposer' and a.asset_type='player';
  v_prop_in:=v_part_out; v_part_in:=v_prop_out;

  if v_prop_cap-v_prop_out+v_prop_in>v_limit then
    return jsonb_build_object('ok',false,'error','Trade blocked: proposer would be over the '||v_limit||'-point contract cap.','proposer_cap_after',v_prop_cap-v_prop_out+v_prop_in,'partner_cap_after',v_partner_cap-v_part_out+v_part_in);
  end if;
  if v_partner_cap-v_part_out+v_part_in>v_limit then
    return jsonb_build_object('ok',false,'error','Trade blocked: partner would be over the '||v_limit||'-point contract cap.','proposer_cap_after',v_prop_cap-v_prop_out+v_prop_in,'partner_cap_after',v_partner_cap-v_part_out+v_part_in);
  end if;
  return jsonb_build_object('ok',true,'proposer_cap_before',v_prop_cap,'partner_cap_before',v_partner_cap,
    'proposer_cap_after',v_prop_cap-v_prop_out+v_prop_in,'partner_cap_after',v_partner_cap-v_part_out+v_part_in,
    'proposer_bid_send',v_give_bid,'partner_bid_send',v_receive_bid);
end;
$$;
revoke all on function public._league_validate_trade(uuid) from public,anon,authenticated;

create or replace function public.league_owner_propose_trade(
  p_room_code text,p_team_id uuid,p_pin text,p_partner_team_id uuid,
  p_give jsonb,p_receive jsonb,p_note text default null
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_room public.rooms%rowtype; v_season uuid; v_trade uuid; item jsonb; v_type text; v_validation jsonb; v_name text;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_team_pin(p_team_id,p_pin) then raise exception 'Team authorization failed.'; end if;
  if p_partner_team_id=p_team_id or not exists(select 1 from public.teams where id=p_partner_team_id and room_id=v_room.id) then raise exception 'Choose another league team.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  insert into public.league_trades(season_id,proposer_team_id,partner_team_id,note) values(v_season,p_team_id,p_partner_team_id,nullif(trim(p_note),'')) returning id into v_trade;

  for item in select * from jsonb_array_elements(coalesce(p_give,'[]'::jsonb)) loop
    v_type:=item->>'type'; v_name:=item->>'name';
    insert into public.league_trade_assets(trade_id,direction,asset_type,asset_key,player_name,pick_id,bid_amount,details)
    values(v_trade,'proposer_to_partner',v_type,item->>'key',v_name,nullif(item->>'pick_id','')::uuid,nullif(item->>'amount','')::integer,item);
  end loop;
  for item in select * from jsonb_array_elements(coalesce(p_receive,'[]'::jsonb)) loop
    v_type:=item->>'type'; v_name:=item->>'name';
    insert into public.league_trade_assets(trade_id,direction,asset_type,asset_key,player_name,pick_id,bid_amount,details)
    values(v_trade,'partner_to_proposer',v_type,item->>'key',v_name,nullif(item->>'pick_id','')::uuid,nullif(item->>'amount','')::integer,item);
  end loop;
  if not exists(select 1 from public.league_trade_assets where trade_id=v_trade) then delete from public.league_trades where id=v_trade; raise exception 'A trade needs at least one asset.'; end if;
  v_validation:=public._league_validate_trade(v_trade);
  if coalesce((v_validation->>'ok')::boolean,false)=false then delete from public.league_trades where id=v_trade; raise exception '%',v_validation->>'error'; end if;
  return jsonb_build_object('ok',true,'trade_id',v_trade,'validation',v_validation);
end;
$$;

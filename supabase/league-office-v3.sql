create or replace function public.league_commish_trade_decision(
  p_room_code text,p_commish_pin text,p_trade_id uuid,p_approve boolean
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_room public.rooms%rowtype; v_trade public.league_trades%rowtype; v_validation jsonb; a record;
  v_from uuid; v_to uuid; v_contract public.league_contracts%rowtype; v_target_years integer; v_tx uuid; v_commish uuid;
  v_prop_name text; v_partner_name text;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  select id into v_commish from public.teams where room_id=v_room.id and name='Weiss Tea & Lemonade';
  select tr.* into v_trade from public.league_trades tr join public.league_seasons s on s.id=tr.season_id where tr.id=p_trade_id and s.room_id=v_room.id for update;
  if v_trade.id is null or v_trade.status<>'pending_commish' then raise exception 'Trade is not awaiting commissioner approval.'; end if;
  if not p_approve then update public.league_trades set status='denied',decided_at=now(),commissioner_team_id=v_commish,updated_at=now() where id=p_trade_id; return jsonb_build_object('ok',true,'status','denied'); end if;
  v_validation:=public._league_validate_trade(p_trade_id);
  if coalesce((v_validation->>'ok')::boolean,false)=false then raise exception '%',v_validation->>'error'; end if;

  -- Transfer players first; active contracts follow with unchanged current term/value.
  for a in select * from public.league_trade_assets where trade_id=p_trade_id and asset_type='player' order by id loop
    v_from:=case when a.direction='proposer_to_partner' then v_trade.proposer_team_id else v_trade.partner_team_id end;
    v_to:=case when a.direction='proposer_to_partner' then v_trade.partner_team_id else v_trade.proposer_team_id end;
    update public.league_roster_entries set team_id=v_to,updated_at=now() where room_id=v_room.id and team_id=v_from and player_key=a.asset_key and active=true;
    select * into v_contract from public.league_contracts where season_id=v_trade.season_id and team_id=v_from and player_key=a.asset_key and status='active' for update;
    if v_contract.id is not null then
      update public.league_contracts set team_id=v_to,source='trade',updated_at=now() where id=v_contract.id;
      update public.league_contract_extension_eligibility set status='superseded' where contract_id=v_contract.id and status='eligible';
      v_target_years:=case v_contract.length_years when 2 then 3 when 3 then 4 else null end;
      if v_target_years is not null then
        insert into public.league_contract_extension_eligibility(season_id,contract_id,trade_id,team_id,eligible_to_years,status)
        values(v_trade.season_id,v_contract.id,p_trade_id,v_to,v_target_years,'eligible');
      end if;
    end if;
    -- Constitution: rookie rights automatically follow a rights player when the player is traded.
    update public.league_rookie_rights set owner_team_id=v_to,updated_at=now()
      where room_id=v_room.id and player_key=a.asset_key and status='active';
  end loop;

  -- Separately traded rights.
  for a in select * from public.league_trade_assets where trade_id=p_trade_id and asset_type='rookie_rights' order by id loop
    v_to:=case when a.direction='proposer_to_partner' then v_trade.partner_team_id else v_trade.proposer_team_id end;
    update public.league_rookie_rights set owner_team_id=v_to,updated_at=now() where room_id=v_room.id and player_key=a.asset_key and status='active';
  end loop;
  -- Future picks.
  for a in select * from public.league_trade_assets where trade_id=p_trade_id and asset_type in ('rookie_pick','supplemental_pick') order by id loop
    v_to:=case when a.direction='proposer_to_partner' then v_trade.partner_team_id else v_trade.proposer_team_id end;
    update public.league_future_picks set owner_team_id=v_to,updated_at=now() where id=a.pick_id and status='active';
  end loop;
  -- Bid dollars.
  for a in select * from public.league_trade_assets where trade_id=p_trade_id and asset_type='bid_dollars' order by id loop
    v_from:=case when a.direction='proposer_to_partner' then v_trade.proposer_team_id else v_trade.partner_team_id end;
    v_to:=case when a.direction='proposer_to_partner' then v_trade.partner_team_id else v_trade.proposer_team_id end;
    update public.teams set remaining_budget=remaining_budget-a.bid_amount where id=v_from;
    update public.teams set remaining_budget=remaining_budget+a.bid_amount where id=v_to;
  end loop;

  update public.league_trades set status='approved',decided_at=now(),commissioner_team_id=v_commish,updated_at=now() where id=p_trade_id;
  select name into v_prop_name from public.teams where id=v_trade.proposer_team_id;
  select name into v_partner_name from public.teams where id=v_trade.partner_team_id;
  v_tx:=public._league_log_transaction(v_trade.season_id,'trade',v_trade.proposer_team_id,v_trade.partner_team_id,null,null,
    'Trade approved: '||v_prop_name||' ↔ '||v_partner_name,0,0,'league_trades',p_trade_id::text,'trade:'||p_trade_id::text,
    jsonb_build_object('trade_id',p_trade_id,'validation',v_validation,'assets',(select coalesce(jsonb_agg(to_jsonb(x) order by x.id),'[]'::jsonb) from public.league_trade_assets x where x.trade_id=p_trade_id)));
  return jsonb_build_object('ok',true,'status','approved','transaction_id',v_tx,'validation',v_validation);
end;
$$;
grant execute on function public.league_commish_trade_decision(text,text,uuid,boolean) to anon,authenticated;

-- ---------------------------------------------------------------------------
-- Contract extensions. Only traded 2yr->3yr or 3yr->4yr contracts are eligible,
-- only in the trade season, only before the commissioner extension deadline.
-- Cost is paid in bid dollars and new contract point value applies immediately.
-- ---------------------------------------------------------------------------
create or replace function public.league_owner_extend_contract(
  p_room_code text,p_team_id uuid,p_pin text,p_eligibility_id uuid
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_room public.rooms%rowtype; v_season public.league_seasons%rowtype; v_e public.league_contract_extension_eligibility%rowtype;
  v_c public.league_contracts%rowtype; v_r public.league_roster_entries%rowtype; v_deadline public.league_deadlines%rowtype;
  v_costrow public.league_extension_costs%rowtype; v_bid_cost integer; v_new_cap integer; v_used integer; v_team public.teams%rowtype; v_tx uuid;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_team_pin(p_team_id,p_pin) then raise exception 'Team authorization failed.'; end if;
  select * into v_season from public.league_seasons where id=public._league_current_season_id(p_room_code);
  select * into v_e from public.league_contract_extension_eligibility where id=p_eligibility_id and season_id=v_season.id and team_id=p_team_id and status='eligible' for update;
  if v_e.id is null then raise exception 'That contract is not extension-eligible.'; end if;
  select * into v_deadline from public.league_deadlines where season_id=v_season.id and deadline_type='contract_extensions' and status='open' order by due_at desc limit 1;
  if v_deadline.id is null then raise exception 'Contract extensions are not currently open.'; end if;
  if v_deadline.auto_lock and now()>v_deadline.due_at then raise exception 'The contract-extension deadline is locked.'; end if;
  select * into v_c from public.league_contracts where id=v_e.contract_id and team_id=p_team_id and status='active' for update;
  if v_c.id is null then raise exception 'Active contract not found.'; end if;
  if not ((v_c.length_years=2 and v_e.eligible_to_years=3) or (v_c.length_years=3 and v_e.eligible_to_years=4)) then raise exception 'Invalid extension path.'; end if;
  select * into v_r from public.league_roster_entries where room_id=v_room.id and team_id=p_team_id and player_key=v_c.player_key and active=true;
  if v_r.id is null then raise exception 'Player is no longer on your roster.'; end if;
  select * into v_costrow from public.league_extension_costs where season_id=v_season.id and position=v_r.position;
  v_bid_cost:=case when v_e.eligible_to_years=3 then v_costrow.cost_2_to_3 else v_costrow.cost_3_to_4 end;
  if v_bid_cost is null then raise exception 'Extension cost is unavailable for this position.'; end if;
  v_new_cap:=case v_e.eligible_to_years when 3 then 25 when 4 then 45 end;
  select * into v_team from public.teams where id=p_team_id for update;
  if v_team.remaining_budget<v_bid_cost then raise exception 'Extension costs % bid dollars; you only have % remaining.',v_bid_cost,v_team.remaining_budget; end if;
  select coalesce(sum(cap_cost),0) into v_used from public.league_contracts where season_id=v_season.id and team_id=p_team_id and status='active' and id<>v_c.id;
  if v_used+v_new_cap>v_season.salary_cap_points then raise exception 'Extension would exceed the % point salary cap.',v_season.salary_cap_points; end if;
  update public.teams set remaining_budget=remaining_budget-v_bid_cost where id=p_team_id;
  update public.league_contracts set length_years=v_e.eligible_to_years,cap_cost=v_new_cap,end_year=start_year+v_e.eligible_to_years-1,source='trade_extension',updated_at=now() where id=v_c.id;
  update public.league_contract_extension_eligibility set status='exercised',exercised_at=now() where id=v_e.id;
  v_tx:=public._league_log_transaction(v_season.id,'contract_extended',p_team_id,null,v_c.player_key,v_c.player_name,
    v_c.player_name||' extended from '||v_c.length_years||' years to '||v_e.eligible_to_years||' years for '||v_bid_cost||' bid dollars',
    -v_bid_cost,v_new_cap-v_c.cap_cost,'league_contracts',v_c.id::text,null,
    jsonb_build_object('from_years',v_c.length_years,'to_years',v_e.eligible_to_years,'from_cap',v_c.cap_cost,'to_cap',v_new_cap,'bid_cost',v_bid_cost,'deadline_id',v_deadline.id,'trade_id',v_e.trade_id));
  return jsonb_build_object('ok',true,'player',v_c.player_name,'bid_cost',v_bid_cost,'new_length',v_e.eligible_to_years,'new_cap_cost',v_new_cap,'transaction_id',v_tx);
end;
$$;
grant execute on function public.league_owner_extend_contract(text,uuid,text,uuid) to anon,authenticated;

-- ---------------------------------------------------------------------------
-- Commissioner correction: preserves audit trail and can adjust bid dollars.
-- ---------------------------------------------------------------------------
create or replace function public.league_commish_correction(
  p_room_code text,p_commish_pin text,p_team_id uuid,p_bid_delta integer,p_description text,p_reverse_transaction_id uuid default null
) returns jsonb
language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_team public.teams%rowtype; v_tx uuid;
begin
  select * into v_room from public.rooms where code=p_room_code;

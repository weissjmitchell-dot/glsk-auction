language plpgsql security definer set search_path=public,pg_temp as $$
declare v_id uuid;
begin
  insert into public.league_transactions(
    season_id,transaction_type,team_id,other_team_id,player_key,player_name,description,
    bid_delta,cap_delta,related_type,related_id,external_key,details
  ) values(
    p_season_id,p_type,p_team_id,p_other_team_id,p_player_key,p_player_name,p_description,
    coalesce(p_bid_delta,0),coalesce(p_cap_delta,0),p_related_type,p_related_id,p_external_key,coalesce(p_details,'{}'::jsonb)
  )
  on conflict(season_id,external_key) where external_key is not null do update
    set description=excluded.description
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.phase3_select_player(p_room_code text,p_team_id uuid,p_pin text,p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null then return jsonb_build_object('ok',false,'error','Room not found.'); end if;
  if not exists(select 1 from public.teams where id=p_team_id and room_id=v_room)
     or not public._valid_team_pin(p_team_id,p_pin) then
    return jsonb_build_object('ok',false,'error','Team authorization failed.');
  end if;
  return public._phase3_select(v_room,p_team_id,p_player_id,false);
end; $$;

create or replace function public.phase3_commish_select_player(p_room_code text,p_commish_pin text,p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_team uuid;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then
    return jsonb_build_object('ok',false,'error','Commissioner authorization failed.');
  end if;
  select public._phase3_team_for_turn(v_room,current_turn_no) into v_team
  from public.phase3_settings where room_id=v_room;
  return public._phase3_select(v_room,v_team,p_player_id,true);
end; $$;

create or replace function public.phase3_commish_start(p_room_code text,p_commish_pin text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_s public.phase3_settings%rowtype; v_turn integer;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then
    return jsonb_build_object('ok',false,'error','Commissioner authorization failed.');
  end if;
  select * into v_s from public.phase3_settings where room_id=v_room for update;
  if v_s.status='complete' then return jsonb_build_object('ok',false,'error','Phase 3 is complete. Reset it before starting again.'); end if;
  v_turn := public._phase3_next_eligible_turn(v_room,v_s.current_turn_no);
  if v_turn is null then
    update public.phase3_settings set status='complete',pick_ends_at=null,updated_at=now() where room_id=v_room;
    return jsonb_build_object('ok',true,'complete',true);
  end if;
  update public.phase3_settings
    set status='live',current_turn_no=v_turn,pick_ends_at=now()+make_interval(secs=>pick_seconds),
        pause_remaining_seconds=null,updated_at=now()
    where room_id=v_room;
  return jsonb_build_object('ok',true);
end; $$;

create or replace function public.phase3_commish_pause(p_room_code text,p_commish_pin text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_s public.phase3_settings%rowtype; v_rem integer;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then return jsonb_build_object('ok',false,'error','Commissioner authorization failed.'); end if;
  select * into v_s from public.phase3_settings where room_id=v_room for update;
  if v_s.status<>'live' then return jsonb_build_object('ok',false,'error','Phase 3 is not live.'); end if;
  v_rem := greatest(0,ceil(extract(epoch from (v_s.pick_ends_at-now())))::integer);
  update public.phase3_settings set status='paused',pause_remaining_seconds=v_rem,pick_ends_at=null,updated_at=now() where room_id=v_room;
  return jsonb_build_object('ok',true);
end; $$;

create or replace function public.phase3_commish_resume(p_room_code text,p_commish_pin text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_s public.phase3_settings%rowtype; v_rem integer;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then return jsonb_build_object('ok',false,'error','Commissioner authorization failed.'); end if;
  select * into v_s from public.phase3_settings where room_id=v_room for update;
  if v_s.status<>'paused' then return jsonb_build_object('ok',false,'error','Phase 3 is not paused.'); end if;
  v_rem := greatest(1,coalesce(v_s.pause_remaining_seconds,v_s.pick_seconds));
  update public.phase3_settings set status='live',pick_ends_at=now()+make_interval(secs=>v_rem),pause_remaining_seconds=null,updated_at=now() where room_id=v_room;
  return jsonb_build_object('ok',true);
end; $$;

create or replace function public.phase3_commish_add_time(p_room_code text,p_commish_pin text,p_seconds integer default 30)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_s public.phase3_settings%rowtype; v_add integer;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then return jsonb_build_object('ok',false,'error','Commissioner authorization failed.'); end if;
  v_add:=greatest(1,least(coalesce(p_seconds,30),600));
  select * into v_s from public.phase3_settings where room_id=v_room for update;
  if v_s.status='paused' then
    update public.phase3_settings set pause_remaining_seconds=coalesce(pause_remaining_seconds,0)+v_add,updated_at=now() where room_id=v_room;
  elsif v_s.status='live' then
    update public.phase3_settings set pick_ends_at=coalesce(pick_ends_at,now())+make_interval(secs=>v_add),updated_at=now() where room_id=v_room;
  else
    return jsonb_build_object('ok',false,'error','Draft must be live or paused to add time.');
  end if;
  return jsonb_build_object('ok',true);
end; $$;


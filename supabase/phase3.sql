create or replace function public.phase3_commish_set_order(p_room_code text,p_commish_pin text,p_team_ids jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_count integer; v_distinct integer;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then return jsonb_build_object('ok',false,'error','Commissioner authorization failed.'); end if;
  if jsonb_typeof(p_team_ids)<>'array' or jsonb_array_length(p_team_ids)<>12 then return jsonb_build_object('ok',false,'error','Draft order must contain exactly 12 teams.'); end if;
  select count(*),count(distinct value) into v_count,v_distinct from jsonb_array_elements_text(p_team_ids);
  if v_count<>12 or v_distinct<>12 then return jsonb_build_object('ok',false,'error','Draft order contains duplicate or missing teams.'); end if;
  if exists(
    select 1 from jsonb_array_elements_text(p_team_ids) x
    where not exists(select 1 from public.teams t where t.room_id=v_room and t.id::text=x.value)
  ) then return jsonb_build_object('ok',false,'error','Draft order contains an invalid team.'); end if;
  delete from public.phase3_order where room_id=v_room;
  insert into public.phase3_order(room_id,slot,team_id)
  select v_room,ordinality,value::uuid from jsonb_array_elements_text(p_team_ids) with ordinality;
  return jsonb_build_object('ok',true);
end; $$;


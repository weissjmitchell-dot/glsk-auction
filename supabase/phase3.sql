create or replace function public.phase3_commish_undo_last_pick(p_room_code text,p_commish_pin text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_pick public.phase3_picks%rowtype;
begin
  select id into v_room from public.rooms where code=p_room_code;
  if v_room is null or not public._valid_commish_pin(v_room,p_commish_pin) then return jsonb_build_object('ok',false,'error','Commissioner authorization failed.'); end if;
  select * into v_pick from public.phase3_picks where room_id=v_room order by pick_no desc limit 1 for update;
  if v_pick.id is null then return jsonb_build_object('ok',false,'error','There is no Phase 3 pick to undo.'); end if;


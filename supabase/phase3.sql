create or replace function public._phase3_team_for_turn(p_room_id uuid,p_turn_no integer)
returns uuid language plpgsql stable security definer set search_path=public,pg_temp as $$
declare v_round integer; v_pos integer; v_slot integer; v_team uuid;
begin
  v_round := ((p_turn_no-1)/12)+1;
  v_pos := ((p_turn_no-1)%12)+1;
  v_slot := case when mod(v_round,2)=1 then v_pos else 13-v_pos end;
  select team_id into v_team from public.phase3_order where room_id=p_room_id and slot=v_slot;
  return v_team;
end; $$;

create or replace function public._phase3_next_eligible_turn(p_room_id uuid,p_start_turn integer)
returns integer language plpgsql stable security definer set search_path=public,pg_temp as $$
declare v_turn integer := greatest(1,p_start_turn); v_team uuid; v_rs public.phase3_roster_state%rowtype; v_i integer := 0;
begin
  if not exists(select 1 from public.phase3_roster_state where room_id=p_room_id and roster_count < max_roster_size) then
    return null;
  end if;
  loop
    v_i := v_i + 1;
    if v_i > 10000 then return null; end if;
    v_team := public._phase3_team_for_turn(p_room_id,v_turn);
    select * into v_rs from public.phase3_roster_state where room_id=p_room_id and team_id=v_team;
    if v_rs.team_id is not null and v_rs.roster_count < v_rs.max_roster_size then return v_turn; end if;
    v_turn := v_turn + 1;
  end loop;
end; $$;

create or replace function public._phase3_advance(p_room_id uuid)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare v_s public.phase3_settings%rowtype; v_next integer;
begin
  select * into v_s from public.phase3_settings where room_id=p_room_id for update;
  if not exists(select 1 from public.phase3_roster_state where room_id=p_room_id and roster_count < max_roster_size) then
    update public.phase3_settings
      set status='complete',pick_ends_at=null,pause_remaining_seconds=null,updated_at=now()
      where room_id=p_room_id;
    return;
  end if;
  v_next := public._phase3_next_eligible_turn(p_room_id,v_s.current_turn_no+1);
  if v_next is null then
    update public.phase3_settings set status='complete',pick_ends_at=null,pause_remaining_seconds=null,updated_at=now() where room_id=p_room_id;
  else
    update public.phase3_settings
      set current_turn_no=v_next,
          pick_ends_at=case when status='live' then now()+make_interval(secs=>pick_seconds) else null end,
          pause_remaining_seconds=null,
          updated_at=now()
      where room_id=p_room_id;
  end if;
end; $$;

create or replace function public._phase3_select(
  p_room_id uuid,p_team_id uuid,p_player_id uuid,p_commish_override boolean default false
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_s public.phase3_settings%rowtype;
  v_expected uuid;
  v_rs public.phase3_roster_state%rowtype;
  v_p public.phase3_players%rowtype;
  v_pick_no integer;
  v_round integer;
  v_pick_id bigint;
begin
  select * into v_s from public.phase3_settings where room_id=p_room_id for update;
  if v_s.status<>'live' then return jsonb_build_object('ok',false,'error','Phase 3 draft is not live.'); end if;

  v_expected := public._phase3_team_for_turn(p_room_id,v_s.current_turn_no);
  if not p_commish_override and p_team_id<>v_expected then
    return jsonb_build_object('ok',false,'error','It is not your turn to pick.');
  end if;
  if p_commish_override then p_team_id := v_expected; end if;

  select * into v_rs from public.phase3_roster_state where room_id=p_room_id and team_id=p_team_id for update;
  if v_rs.team_id is null then return jsonb_build_object('ok',false,'error','Roster state was not found.'); end if;
  if v_rs.roster_count>=v_rs.max_roster_size then
    return jsonb_build_object('ok',false,'error','That team already has a full roster.');
  end if;

  select * into v_p from public.phase3_players where room_id=p_room_id and id=p_player_id for update;
  if v_p.id is null or v_p.status<>'available' then
    return jsonb_build_object('ok',false,'error','That player is no longer available.');
  end if;

  select coalesce(max(pick_no),0)+1 into v_pick_no from public.phase3_picks where room_id=p_room_id;
  v_round := ((v_s.current_turn_no-1)/12)+1;

  insert into public.phase3_picks(room_id,pick_no,turn_no,round,team_id,player_id)
  values(p_room_id,v_pick_no,v_s.current_turn_no,v_round,p_team_id,p_player_id)
  returning id into v_pick_id;

  update public.phase3_players
    set status='drafted',drafted_team_id=p_team_id,drafted_turn_no=v_s.current_turn_no
    where id=p_player_id;

  update public.phase3_roster_state
    set roster_count=roster_count+1
    where room_id=p_room_id and team_id=p_team_id;

  insert into public.phase3_roster_entries(room_id,team_id,player_name,nfl_team,position,source,phase3_pick_id)
  values(p_room_id,p_team_id,v_p.name,v_p.nfl_team,v_p.position,'phase3',v_pick_id);

  perform public._phase3_advance(p_room_id);
  return jsonb_build_object('ok',true,'player',v_p.name,'pick_no',v_pick_no,'team_id',p_team_id);
end; $$;

-- ---------------------------------------------------------------------------

  update public.phase3_settings
    set status='live',current_turn_no=v_pick.turn_no,pick_ends_at=now()+make_interval(secs=>pick_seconds),
        pause_remaining_seconds=null,updated_at=now()
    where room_id=v_room;
  return jsonb_build_object('ok',true,'pick_no',v_pick.pick_no,'turn_no',v_pick.turn_no);
end; $$;


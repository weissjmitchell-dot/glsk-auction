-- GLSK opt-in email alerts. No email is sent until a verified provider
-- is configured on the Vercel GLSK project (RESEND_API_KEY, GLSK_EMAIL_FROM).
-- New members and existing members are OFF by default.
begin;

create table if not exists public.league_email_preferences (
 room_id uuid not null references public.rooms(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 category text not null check(category in (
  'trades','roster_moves','drafts','contracts','rookie_rights',
  'message_board','league_chat','deadlines','matchups',
  'injuries','player_availability','other_activity'
 )),
 enabled boolean not null default false,
 updated_at timestamptz not null default now(),
 primary key(room_id,user_id,category)
);
alter table public.league_email_preferences enable row level security;
revoke all on public.league_email_preferences from public,anon,authenticated;

create table if not exists public.league_email_deliveries (
 id bigint generated by default as identity primary key,
 event_id bigint not null references public.league_events(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'pending' check(status in ('pending','sent','failed')),
 provider_id text,
 created_at timestamptz not null default now(),
 reported_at timestamptz,
 unique(event_id,user_id)
);
alter table public.league_email_deliveries enable row level security;
revoke all on public.league_email_deliveries from public,anon,authenticated;

create or replace function public.league_get_email_preferences(p_room_code text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_user uuid:=auth.uid(); v_prefs jsonb;
begin
 select id into v_room from public.rooms where code=p_room_code;
 if v_user is null or v_room is null or not exists(
  select 1 from public.league_owner_accounts a
  where a.room_id=v_room and a.user_id=v_user and a.active=true
 ) then return jsonb_build_object('ok',false,'error','GLSK owner sign-in required.'); end if;
 select coalesce(jsonb_agg(jsonb_build_object('category',p.category,'enabled',p.enabled)),'[]'::jsonb)
 into v_prefs from public.league_email_preferences p
 where p.room_id=v_room and p.user_id=v_user;
 return jsonb_build_object('ok',true,'preferences',v_prefs);
end $$;
revoke all on function public.league_get_email_preferences(text) from public,anon;
grant execute on function public.league_get_email_preferences(text) to authenticated;

create or replace function public.league_set_email_preference(
 p_room_code text,p_category text,p_enabled boolean
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_user uuid:=auth.uid();
begin
 if p_category is null or p_category<>all(array[
  'trades','roster_moves','drafts','contracts','rookie_rights',
  'message_board','league_chat','deadlines','matchups',
  'injuries','player_availability','other_activity'
 ]::text[]) then return jsonb_build_object('ok',false,'error','Invalid email category.'); end if;
 select id into v_room from public.rooms where code=p_room_code;
 if v_user is null or v_room is null or not exists(
  select 1 from public.league_owner_accounts a
  where a.room_id=v_room and a.user_id=v_user and a.active=true
 ) then return jsonb_build_object('ok',false,'error','GLSK owner sign-in required.'); end if;
 insert into public.league_email_preferences(room_id,user_id,category,enabled)
 values(v_room,v_user,p_category,coalesce(p_enabled,false))
 on conflict(room_id,user_id,category) do update
 set enabled=excluded.enabled,updated_at=now();
 return jsonb_build_object('ok',true);
end $$;
revoke all on function public.league_set_email_preference(text,text,boolean) from public,anon;
grant execute on function public.league_set_email_preference(text,text,boolean) to authenticated;

-- Called only by GLSK's existing authenticated server webhook.
-- Return just confirmed, active, opted-in recipients for this event.
-- A unique delivery row prevents duplicate email on webhook retries.
create or replace function public.league_email_delivery_claim(
 p_event_id bigint,p_webhook_secret text
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare
 v_event public.league_events%rowtype;
 v_r record; v_id bigint; v_dest jsonb:='[]'::jsonb;
begin
 if p_webhook_secret is null or not exists(
  select 1 from public.league_push_config
  where enabled=true and webhook_secret=p_webhook_secret
 ) then return jsonb_build_object('ok',false,'error','Unauthorized.'); end if;
 select * into v_event from public.league_events where id=p_event_id;
 if v_event.id is null then return jsonb_build_object('ok',false,'error','Event not found.'); end if;
 for v_r in
  select distinct a.user_id,u.email
  from public.league_owner_accounts a
  join auth.users u on u.id=a.user_id
  join public.league_email_preferences p on p.room_id=a.room_id
    and p.user_id=a.user_id and p.category=v_event.category and p.enabled=true
  where a.room_id=v_event.room_id and a.active=true
    and u.email is not null and u.email_confirmed_at is not null
    and (v_event.visibility='league' or v_event.target_team_id=a.team_id)
    and (
      v_event.category<>'injuries'
      or exists(
       select 1 from public.league_roster_entries re
       where re.room_id=v_event.room_id and re.team_id=a.team_id
         and re.player_key=v_event.player_key and re.active=true
      )
      or exists(
       select 1 from public.league_player_watches w
       where w.room_id=v_event.room_id and w.team_id=a.team_id
        and w.player_key=v_event.player_key and w.injury_alerts=true
        and (w.user_id=a.user_id or w.user_id is null)
      )
    )
    and (
      v_event.category<>'player_availability'
      or exists(
       select 1 from public.league_player_watches w
       where w.room_id=v_event.room_id and w.team_id=a.team_id
        and w.player_key=v_event.player_key and w.availability_alerts=true
        and (w.user_id=a.user_id or w.user_id is null)
      )
    )
 loop
  v_id:=null;
  insert into public.league_email_deliveries(event_id,user_id)
  values(v_event.id,v_r.user_id)
  on conflict(event_id,user_id) do nothing returning id into v_id;
  if v_id is not null then
    v_dest:=v_dest||jsonb_build_array(jsonb_build_object('id',v_id,'email',v_r.email));
  end if;
 end loop;
 return jsonb_build_object('ok',true,'event',jsonb_build_object(
  'id',v_event.id,'title',v_event.title,'body',v_event.body,
  'category',v_event.category
 ),'recipients',v_dest);
end $$;
revoke all on function public.league_email_delivery_claim(bigint,text) from public;
grant execute on function public.league_email_delivery_claim(bigint,text) to anon,authenticated;

create or replace function public.league_email_delivery_report(
 p_delivery_id bigint,p_webhook_secret text,p_success boolean,p_provider_id text default null
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if p_webhook_secret is null or not exists(
  select 1 from public.league_push_config
  where enabled=true and webhook_secret=p_webhook_secret
 ) then return jsonb_build_object('ok',false,'error','Unauthorized.'); end if;
 update public.league_email_deliveries
 set status=case when p_success then 'sent' else 'failed' end,
  provider_id=left(p_provider_id,200),reported_at=now()
 where id=p_delivery_id and status='pending';
 return jsonb_build_object('ok',true);
end $$;
revoke all on function public.league_email_delivery_report(bigint,text,boolean,text) from public;
grant execute on function public.league_email_delivery_report(bigint,text,boolean,text) to anon,authenticated;


-- Sanity check: current roster totals should match the Phase 3 roster snapshot.
select
  count(*) filter(where active) as active_roster_players,
  count(distinct team_id) filter(where active) as teams_with_rosters
from public.league_roster_entries
where room_id=(select id from public.rooms where code='GLSK26');

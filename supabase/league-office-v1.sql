 values(v_season,p_team_id,p_category,trim(p_description),p_amount_cents,p_status,p_due_at,case when p_status='paid' then now() else null end) returning id into v_id;
 insert into public.league_audit_log(season_id,action,entity_type,entity_id,details) values(v_season,'add_finance','league_finance_items',v_id::text,jsonb_build_object('team_id',p_team_id,'category',p_category,'amount_cents',p_amount_cents));

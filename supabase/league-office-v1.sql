-- Helper: current season id.
create or replace function public._league_current_season_id(p_room_code text)
returns uuid language sql stable security definer set search_path=public,pg_temp as $$
  select ls.id from public.league_seasons ls join public.rooms r on r.id=ls.room_id
  where r.code=p_room_code and ls.is_current order by ls.season_year desc limit 1;
$$;

-- Commissioner: save generic numeric rule settings.
create or replace function public.league_commish_set_rules(p_room_code text,p_commish_pin text,p_updates jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_item jsonb; v_key text; v_value numeric;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  for v_item in select * from jsonb_array_elements(coalesce(p_updates,'[]'::jsonb)) loop
    v_key:=v_item->>'key'; v_value:=(v_item->>'value')::numeric;
    if v_value < 0 or v_value > 10000 then raise exception 'Invalid value for %',v_key; end if;
    update public.league_rule_settings set numeric_value=v_value,updated_at=now() where season_id=v_season and rule_key=v_key and not locked;
  end loop;
  update public.league_seasons ls set roster_limit=coalesce((select numeric_value::int from public.league_rule_settings where season_id=v_season and rule_key='roster_limit'),ls.roster_limit),
    salary_cap_points=coalesce((select numeric_value::int from public.league_rule_settings where season_id=v_season and rule_key='salary_cap_points'),ls.salary_cap_points)
  where id=v_season;
  insert into public.league_audit_log(season_id,action,entity_type,details) values(v_season,'update_rules','league_rule_settings',jsonb_build_object('updates',p_updates));
  return jsonb_build_object('ok',true);
end; $$;

-- Commissioner: save redistribution; requires exactly 12 rows and 100% total.
create or replace function public.league_commish_save_redistribution(p_room_code text,p_commish_pin text,p_rows jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_count int; v_total numeric; v_item jsonb;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  v_season:=public._league_current_season_id(p_room_code);
  select count(*),coalesce(sum((x->>'percentage')::numeric),0) into v_count,v_total from jsonb_array_elements(p_rows) x;
  if v_count<>12 then raise exception 'Redistribution requires exactly 12 finish rows.'; end if;
  if abs(v_total-100)>0.0005 then raise exception 'Redistribution must total 100%%. Current total: %',v_total; end if;
  for v_item in select * from jsonb_array_elements(p_rows) loop
    update public.redistribution_rules
    set percentage=(v_item->>'percentage')::numeric,updated_at=now()
    where season_id=v_season and bracket=v_item->>'bracket' and finish=(v_item->>'finish')::int;
  end loop;
  insert into public.league_audit_log(season_id,action,entity_type,details) values(v_season,'update_redistribution','redistribution_rules',jsonb_build_object('rows',p_rows));
  return jsonb_build_object('ok',true,'total',v_total);
end; $$;

-- Commissioner: contract create/update, with cap validation.
create or replace function public.league_commish_upsert_contract(p_room_code text,p_commish_pin text,p_team_id uuid,p_player_name text,p_length_years integer,p_start_year integer)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_cost int; v_cap int; v_used int; v_key text; v_id bigint;
begin
  select * into v_room from public.rooms where code=p_room_code;
  if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
  if not exists(select 1 from public.teams where id=p_team_id and room_id=v_room.id) then raise exception 'Team not found.'; end if;
  v_season:=public._league_current_season_id(p_room_code); v_key:=public._league_roster_key(p_player_name);
  select cap_cost into v_cost from public.contract_options where season_id=v_season and years=p_length_years and active;
  if v_cost is null then raise exception 'That contract length is not enabled.'; end if;
  select salary_cap_points into v_cap from public.league_seasons where id=v_season;
  select coalesce(sum(cap_cost),0) into v_used from public.league_contracts where season_id=v_season and team_id=p_team_id and status='active' and player_key<>v_key;
  if v_used+v_cost>v_cap then raise exception 'Contract would exceed the % point salary cap.',v_cap; end if;
  insert into public.league_contracts(season_id,team_id,player_key,player_name,start_year,end_year,length_years,cap_cost,status,source)
  values(v_season,p_team_id,v_key,trim(p_player_name),p_start_year,p_start_year+p_length_years-1,p_length_years,v_cost,'active','commissioner')
  on conflict(season_id,player_key) do update set team_id=excluded.team_id,player_name=excluded.player_name,start_year=excluded.start_year,end_year=excluded.end_year,
    length_years=excluded.length_years,cap_cost=excluded.cap_cost,status='active',source='commissioner',updated_at=now()
  returning id into v_id;
  insert into public.league_audit_log(season_id,action,entity_type,entity_id,details) values(v_season,'upsert_contract','league_contracts',v_id::text,jsonb_build_object('team_id',p_team_id,'player',p_player_name,'years',p_length_years,'cost',v_cost));
  return jsonb_build_object('ok',true,'contract_id',v_id,'cap_used',v_used+v_cost,'cap_limit',v_cap);
end; $$;

create or replace function public.league_commish_void_contract(p_room_code text,p_commish_pin text,p_contract_id bigint)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid;
begin
 select * into v_room from public.rooms where code=p_room_code;
 if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
 v_season:=public._league_current_season_id(p_room_code);
 update public.league_contracts set status='void',updated_at=now() where id=p_contract_id and season_id=v_season;
 insert into public.league_audit_log(season_id,action,entity_type,entity_id) values(v_season,'void_contract','league_contracts',p_contract_id::text);
 return jsonb_build_object('ok',true);
end; $$;

-- Deadlines.
create or replace function public.league_commish_create_deadline(p_room_code text,p_commish_pin text,p_title text,p_deadline_type text,p_due_at timestamptz,p_auto_lock boolean,p_notes text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_id uuid;
begin
 select * into v_room from public.rooms where code=p_room_code;
 if v_room.id is null or not public._valid_commish_pin(v_room.id,p_commish_pin) then raise exception 'Commissioner authorization failed.'; end if;
 if length(trim(p_title))<2 then raise exception 'Deadline title is required.'; end if;
 v_season:=public._league_current_season_id(p_room_code);
 insert into public.league_deadlines(season_id,title,deadline_type,due_at,auto_lock,notes) values(v_season,trim(p_title),coalesce(nullif(trim(p_deadline_type),''),'general'),p_due_at,coalesce(p_auto_lock,true),nullif(trim(p_notes),'')) returning id into v_id;
 insert into public.league_deadline_team_status(deadline_id,team_id) select v_id,t.id from public.teams t where t.room_id=v_room.id on conflict do nothing;
 insert into public.league_audit_log(season_id,action,entity_type,entity_id,details) values(v_season,'create_deadline','league_deadlines',v_id::text,jsonb_build_object('title',p_title,'due_at',p_due_at));
 return jsonb_build_object('ok',true,'deadline_id',v_id);
end; $$;

create or replace function public.league_mark_deadline_submitted(p_room_code text,p_team_id uuid,p_pin text,p_deadline_id uuid)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_due timestamptz; v_lock boolean; v_new text;
begin
 select * into v_room from public.rooms where code=p_room_code;
 if v_room.id is null or not public._valid_team_pin(p_team_id,p_pin) then raise exception 'Team authorization failed.'; end if;
 select d.due_at,d.auto_lock into v_due,v_lock from public.league_deadlines d join public.league_seasons s on s.id=d.season_id where d.id=p_deadline_id and s.room_id=v_room.id and d.status='open';
 if v_due is null then raise exception 'Deadline is not open.'; end if;
 if now()>v_due and v_lock then raise exception 'This deadline is locked.'; end if;
 v_new:=case when now()>v_due then 'late' else 'submitted' end;
 insert into public.league_deadline_team_status(deadline_id,team_id,status,submitted_at,updated_at) values(p_deadline_id,p_team_id,v_new,now(),now())
 on conflict(deadline_id,team_id) do update set status=excluded.status,submitted_at=excluded.submitted_at,updated_at=now();
 return jsonb_build_object('ok',true,'status',v_new);
end; $$;

create or replace function public.league_commish_set_deadline_status(p_room_code text,p_commish_pin text,p_deadline_id uuid,p_status text)

-- GREAT LAKE STATE KEEPERS — LEAGUE OFFICE FOUNDATION v1
-- Adds season-aware league management tables for contracts, rules, deadlines,
-- redistribution, finances and audit history. Safe to run on the existing GLSK26 database.
-- Does NOT reset or alter draft rooms, PINs, bids, sales, rosters, Supplemental or Phase 3 state.

begin;

create table if not exists public.league_seasons (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  season_year integer not null,
  status text not null default 'active' check(status in ('setup','active','complete','archived')),
  roster_limit integer not null default 18 check(roster_limit between 1 and 100),
  salary_cap_points integer not null default 100 check(salary_cap_points between 1 and 10000),
  is_current boolean not null default false,
  created_at timestamptz not null default now(),
  unique(room_id, season_year)
);
create unique index if not exists league_seasons_current_one
  on public.league_seasons(room_id) where is_current;

create table if not exists public.league_rule_settings (
  id bigint generated by default as identity primary key,
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  rule_key text not null,
  category text not null,
  label text not null,
  numeric_value numeric,
  text_value text,
  boolean_value boolean,
  unit text,
  sort_order integer not null default 0,
  locked boolean not null default false,
  updated_at timestamptz not null default now(),
  unique(season_id, rule_key)
);

create table if not exists public.redistribution_rules (
  id bigint generated by default as identity primary key,
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  bracket text not null check(bracket in ('championship','consolation')),
  finish integer not null check(finish between 1 and 6),
  label text not null,
  percentage numeric(7,3) not null check(percentage >= 0 and percentage <= 100),
  sort_order integer not null,
  updated_at timestamptz not null default now(),
  unique(season_id, bracket, finish)
);

create table if not exists public.contract_options (
  id bigint generated by default as identity primary key,
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  years integer not null check(years between 1 and 10),
  cap_cost integer not null check(cap_cost >= 0),
  active boolean not null default true,
  unique(season_id, years)
);

create table if not exists public.league_contracts (
  id bigint generated by default as identity primary key,
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  team_id uuid not null references public.teams(id),
  player_key text not null,
  player_name text not null,
  start_year integer not null,
  end_year integer not null,
  length_years integer not null check(length_years between 1 and 10),
  cap_cost integer not null check(cap_cost >= 0),
  status text not null default 'active' check(status in ('active','expired','released','traded','void')),
  source text not null default 'import',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(season_id, player_key)
);
create index if not exists league_contracts_team_idx on public.league_contracts(season_id,team_id,status);

create table if not exists public.league_deadlines (
  id uuid primary key default gen_random_uuid(),
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  title text not null,
  deadline_type text not null default 'general',
  due_at timestamptz not null,
  auto_lock boolean not null default true,
  allow_commish_override boolean not null default true,
  status text not null default 'open' check(status in ('open','closed','completed','cancelled')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.league_deadline_team_status (
  deadline_id uuid not null references public.league_deadlines(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete cascade,
  status text not null default 'pending' check(status in ('pending','submitted','late','waived')),
  submitted_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key(deadline_id, team_id)
);

-- Finance rows intentionally have NO public SELECT policy. Access is through PIN-validated RPCs below.
create table if not exists public.league_finance_items (
  id uuid primary key default gen_random_uuid(),
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  team_id uuid references public.teams(id),
  category text not null check(category in ('dues','prize','expense','adjustment','other')),
  description text not null,
  amount_cents integer not null,
  status text not null default 'due' check(status in ('due','paid','waived')),
  due_at date,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists league_finance_team_idx on public.league_finance_items(season_id,team_id,status);

create table if not exists public.league_audit_log (
  id bigint generated by default as identity primary key,
  season_id uuid not null references public.league_seasons(id) on delete cascade,
  actor_team_id uuid references public.teams(id),
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);


 return jsonb_build_object('ok',true);
end; $$;

-- Secure finance read: owner sees only own team; commissioner sees all.
create or replace function public.league_get_finances(p_room_code text,p_team_id uuid,p_pin text,p_commish_pin text default null)
returns setof public.league_finance_items language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room public.rooms%rowtype; v_season uuid; v_commish boolean:=false;
begin
 select * into v_room from public.rooms where code=p_room_code; if v_room.id is null then return; end if;
 v_season:=public._league_current_season_id(p_room_code);
 if p_commish_pin is not null then v_commish:=public._valid_commish_pin(v_room.id,p_commish_pin); end if;
 if v_commish then return query select * from public.league_finance_items where season_id=v_season order by created_at desc; end if;
 if p_team_id is null or not public._valid_team_pin(p_team_id,p_pin) then raise exception 'Team authorization failed.'; end if;
 return query select * from public.league_finance_items where season_id=v_season and team_id=p_team_id order by created_at desc;
end; $$;


create or replace function public.submit_bid(p_room_code text, p_team_id uuid, p_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_room public.rooms%rowtype;
  v_team public.teams%rowtype;
  v_next integer;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null then return jsonb_build_object('ok', false, 'error', 'Room not found.'); end if;
  if v_room.status <> 'live' then return jsonb_build_object('ok', false, 'error', 'The auction is not live.'); end if;
  if v_room.active_player_id is null then return jsonb_build_object('ok', false, 'error', 'No player is currently on the block.'); end if;
  if v_room.auction_ends_at is null or now() >= v_room.auction_ends_at then return jsonb_build_object('ok', false, 'error', 'That auction has expired.'); end if;
  if not public._valid_team_pin(p_team_id, p_pin) then return jsonb_build_object('ok', false, 'error', 'Your team PIN is no longer valid.'); end if;
  if v_room.active_bidder_team_id = p_team_id then return jsonb_build_object('ok', false, 'error', 'You already have the high bid.'); end if;

  select * into v_team from public.teams where id = p_team_id and room_id = v_room.id for update;
  if v_team.id is null then return jsonb_build_object('ok', false, 'error', 'Team not found.'); end if;

  v_next := case when v_room.active_bid = 0 then v_room.min_bid else v_room.active_bid + v_room.bid_increment end;
  if v_team.remaining_budget < v_next then return jsonb_build_object('ok', false, 'error', 'You do not have enough bid dollars remaining.'); end if;

  update public.rooms
  set active_bid = v_next,
      active_bidder_team_id = p_team_id,
      auction_ends_at = now() + make_interval(secs => timer_seconds)
  where id = v_room.id;

  insert into public.bids(room_id, player_id, team_id, amount)
  values (v_room.id, v_room.active_player_id, p_team_id, v_next);

  return jsonb_build_object('ok', true, 'bid', v_next);
end;
$$;

create or replace function public.finalize_if_expired(p_room_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_room public.rooms%rowtype;
  v_total integer;
  v_new_sold integer;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null then return jsonb_build_object('ok', false, 'error', 'Room not found.'); end if;
  if v_room.status <> 'live' or v_room.active_player_id is null or v_room.auction_ends_at is null or now() < v_room.auction_ends_at then
    return jsonb_build_object('ok', true, 'finalized', false);
  end if;

  if v_room.active_bidder_team_id is null or v_room.active_bid = 0 then
    update public.players set status = 'available', queue_order = null where id = v_room.active_player_id;
    update public.rooms set active_player_id = null, active_bid = 0, active_bidder_team_id = null, auction_ends_at = null where id = v_room.id;
    perform public._activate_next(v_room.id);
    return jsonb_build_object('ok', true, 'finalized', true, 'sold', false);
  end if;

  perform 1 from public.teams where id = v_room.active_bidder_team_id for update;
  update public.teams
  set remaining_budget = remaining_budget - v_room.active_bid
  where id = v_room.active_bidder_team_id and remaining_budget >= v_room.active_bid;
  if not found then return jsonb_build_object('ok', false, 'error', 'Winning team no longer has sufficient budget. Commissioner intervention required.'); end if;

  update public.players
  set status = 'sold', sold_team_id = v_room.active_bidder_team_id, sold_price = v_room.active_bid, queue_order = null
  where id = v_room.active_player_id;

  insert into public.sales(room_id, player_id, team_id, price)
  values (v_room.id, v_room.active_player_id, v_room.active_bidder_team_id, v_room.active_bid);

  v_new_sold := v_room.sold_count + 1;
  select count(*) into v_total from public.players where room_id = v_room.id;

  update public.rooms
  set active_player_id = null,
      active_bid = 0,
      active_bidder_team_id = null,
      auction_ends_at = null,
      sold_count = v_new_sold,
      status = case when v_new_sold >= v_total then 'complete' else status end
  where id = v_room.id;

  if v_new_sold < v_total then perform public._activate_next(v_room.id); end if;
  return jsonb_build_object('ok', true, 'finalized', true, 'sold', true, 'sold_count', v_new_sold);
end;
$$;


create or replace function public.commish_force_sale(p_room_code text, p_commish_pin text, p_team_id uuid, p_price integer)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_room public.rooms%rowtype; v_total integer; v_new_sold integer;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null or not public._valid_commish_pin(v_room.id, p_commish_pin) then return jsonb_build_object('ok', false, 'error', 'Commissioner authorization failed.'); end if;
  if v_room.active_player_id is null then return jsonb_build_object('ok', false, 'error', 'No active player.'); end if;
  if p_price is null or p_price < 1 then return jsonb_build_object('ok', false, 'error', 'Sale price must be at least $1.'); end if;
  perform 1 from public.teams where id = p_team_id and room_id = v_room.id and remaining_budget >= p_price for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'Selected team does not have enough bid dollars.'); end if;

  update public.teams set remaining_budget = remaining_budget - p_price where id = p_team_id;
  update public.players set status = 'sold', sold_team_id = p_team_id, sold_price = p_price, queue_order = null where id = v_room.active_player_id;
  insert into public.sales(room_id, player_id, team_id, price) values(v_room.id, v_room.active_player_id, p_team_id, p_price);
  v_new_sold := v_room.sold_count + 1;
  select count(*) into v_total from public.players where room_id = v_room.id;
  update public.rooms set active_player_id = null, active_bid = 0, active_bidder_team_id = null, auction_ends_at = null, sold_count = v_new_sold, status = case when v_new_sold >= v_total then 'complete' else status end where id = v_room.id;
  if v_new_sold < v_total and v_room.status = 'live' then perform public._activate_next(v_room.id); end if;
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.commish_undo_last_sale(p_room_code text, p_commish_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_room public.rooms%rowtype; v_sale public.sales%rowtype;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null or not public._valid_commish_pin(v_room.id, p_commish_pin) then return jsonb_build_object('ok', false, 'error', 'Commissioner authorization failed.'); end if;
  select * into v_sale from public.sales where room_id = v_room.id and undone = false order by sold_at desc limit 1 for update;
  if v_sale.id is null then return jsonb_build_object('ok', false, 'error', 'There is no completed sale to undo.'); end if;
  perform 1 from public.teams where id = v_sale.team_id for update;
  update public.teams set remaining_budget = remaining_budget + v_sale.price where id = v_sale.team_id;
  update public.players set status = 'available', sold_team_id = null, sold_price = null, queue_order = null where id = v_sale.player_id;
  update public.sales set undone = true where id = v_sale.id;
  update public.rooms set sold_count = greatest(0, sold_count - 1), status = case when status = 'complete' then 'live' else status end where id = v_room.id;
  return jsonb_build_object('ok', true);
end;
$$;


create or replace function public.commish_reset_draft(p_room_code text, p_commish_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_room public.rooms%rowtype; v_player_count integer; v_team_count integer;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null then return jsonb_build_object('ok', false, 'error', 'Room not found.'); end if;
  if not public._valid_commish_pin(v_room.id, p_commish_pin) then return jsonb_build_object('ok', false, 'error', 'Commissioner authorization failed.'); end if;

  delete from public.bids where room_id = v_room.id;
  delete from public.sales where room_id = v_room.id;
  update public.teams set remaining_budget = starting_budget where room_id = v_room.id;
  get diagnostics v_team_count = row_count;
  update public.players set status = 'queued', queue_order = rank, sold_team_id = null, sold_price = null where room_id = v_room.id;
  get diagnostics v_player_count = row_count;
  update public.rooms set status = 'setup', active_player_id = null, active_bid = 0, active_bidder_team_id = null, auction_ends_at = null, pause_remaining_seconds = null, sold_count = 0 where id = v_room.id;
  return jsonb_build_object('ok', true, 'teams_restored', v_team_count, 'players_restored', v_player_count);
end;
$$;


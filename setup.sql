-- Internal helper. Caller must already hold a lock on the room row.
create or replace function public._activate_next(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_next uuid;
  v_timer integer;
begin
  select p.id into v_next
  from public.players p
  where p.room_id = p_room_id and p.status = 'queued'
  order by p.queue_order nulls last, p.rank
  limit 1
  for update;

  if v_next is null then
    return;
  end if;

  select timer_seconds into v_timer from public.rooms where id = p_room_id;

  update public.players
  set status = 'active', queue_order = null
  where id = v_next;

  update public.rooms
  set active_player_id = v_next,
      active_bid = 0,
      active_bidder_team_id = null,
      auction_ends_at = now() + make_interval(secs => v_timer),
      pause_remaining_seconds = null
  where id = p_room_id;
end;
$$;

create or replace function public.join_room(p_room_code text, p_team_id uuid, p_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_room uuid;
begin
  select r.id into v_room
  from public.rooms r
  join public.teams t on t.room_id = r.id
  where r.code = p_room_code and t.id = p_team_id;

  if v_room is null then return jsonb_build_object('ok', false, 'error', 'Team not found in this room.'); end if;
  if not public._valid_team_pin(p_team_id, p_pin) then return jsonb_build_object('ok', false, 'error', 'Incorrect team PIN.'); end if;
  return jsonb_build_object('ok', true, 'team_id', p_team_id);
end;
$$;


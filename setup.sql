create or replace function public.commish_pause_draft(p_room_code text, p_commish_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_room public.rooms%rowtype; v_left integer;
begin
  select * into v_room from public.rooms where code = p_room_code for update;
  if v_room.id is null or not public._valid_commish_pin(v_room.id, p_commish_pin) then return jsonb_build_object('ok', false, 'error', 'Commissioner authorization failed.'); end if;
  if v_room.status <> 'live' then return jsonb_build_object('ok', false, 'error', 'Auction is not live.'); end if;
  v_left := case when v_room.auction_ends_at is null then null else greatest(1, ceil(extract(epoch from (v_room.auction_ends_at - now())))::integer) end;
  update public.rooms set status = 'paused', pause_remaining_seconds = v_left, auction_ends_at = null where id = v_room.id;
  return jsonb_build_object('ok', true);
end;
$$;

